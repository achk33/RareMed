const dictionaries: Record<LocaleCode, Record<MessageKey, string>> = { en, fr, ar, ary };

function isRtl(locale: LocaleCode) {
  return locale === "ar" || locale === "ary";
}

const localeListeners = new Set<() => void>();

function readLocale(): LocaleCode {
  const stored = window.localStorage.getItem("raremed.locale");
  if (stored === "en" || stored === "fr" || stored === "ar" || stored === "ary") return stored;
  return "en";
}

function subscribeLocale(listener: () => void) {
  localeListeners.add(listener);
  return () => localeListeners.delete(listener);
}

function writeLocale(next: LocaleCode) {
  window.localStorage.setItem("raremed.locale", next);
  localeListeners.forEach((listener) => listener());
}

type LocaleContextValue = {
  locale: LocaleCode;
  direction: "ltr" | "rtl";
  setLocale: (locale: LocaleCode) => void;
  t: (key: MessageKey) => string;
};

const LocaleContext = createContext<LocaleContextValue | null>(null);

export function LocaleProvider({ children }: { children: ReactNode }) {
  const locale = useSyncExternalStore(subscribeLocale, readLocale, () => "en" as LocaleCode);
  const setLocale = useCallback((next: LocaleCode) => {
    writeLocale(next);
  }, []);

  useEffect(() => {
    document.documentElement.lang = locale === "ary" ? "ar-MA" : locale;
    document.documentElement.dir = isRtl(locale) ? "rtl" : "ltr";
  }, [locale]);

  const value = useMemo<LocaleContextValue>(
    () => ({
      locale,
      direction: isRtl(locale) ? "rtl" : "ltr",
      setLocale,
      t: (key) => dictionaries[locale][key],
    }),
    [locale, setLocale],
  );

  return (
    <LocaleContext.Provider value={value}>
      <DirectionProvider direction={value.direction}>{children}</DirectionProvider>
    </LocaleContext.Provider>
  );
}

export function useLocale() {
  const value = useContext(LocaleContext);
  if (!value) {
    throw new Error("useLocale must be used within LocaleProvider");
  }
  return value;
}
